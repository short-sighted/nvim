assert(vim.wo.colorcolumn == "", "Unexpected selection-like column highlight")
local toggle = vim.fn.maparg("<leader>tc", "n", false, true).callback
toggle()
assert(vim.wo.colorcolumn == "100", "Column guide toggle missing")
toggle()
assert(vim.wo.colorcolumn == "", "Column guide did not clear")
local root = vim.fn.tempname()
vim.fn.mkdir(root, "p")
vim.o.undodir = root
vim.cmd.enew()
local target = vim.api.nvim_get_current_buf()
vim.api.nvim_buf_set_lines(target, 0, -1, false, { "first" })
vim.cmd("set undolevels=10000")
vim.api.nvim_buf_set_lines(target, 0, -1, false, { "second" })
vim.cmd.undo()
vim.cmd("set undolevels=10000")
vim.api.nvim_buf_set_lines(target, 0, -1, false, { "branch" })
assert(#vim.fn.undotree().entries >= 2, "Undo branches not recorded")
vim.cmd.UndotreeToggle()
assert(vim.bo.filetype == "undotree", "Undo panel not focused")
local map = vim.fn.maparg("<CR>", "n", false, true)
assert(map.rhs and map.rhs:find("Undotree"), "Undo selection missing")
vim.cmd.UndotreeToggle()
assert(vim.api.nvim_get_current_buf() == target, "Undo panel did not return to file")
local file = root .. "/history.txt"
vim.cmd.write(file)
assert(vim.uv.fs_stat(vim.fn.undofile(file)), "Persistent undo missing")
vim.fn.delete(root, "rf")
print("Undotree branching, panel focus, selection and persistent undo passed")
vim.cmd("qa!")
